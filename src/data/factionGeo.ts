const mask: Uint8Array = (() => {
  const m = new Uint8Array(COLS * ROWS);
  for (const key of Object.keys(LAND)) {
    const r = Number(key);
    for (const [a, b] of LAND[r]) {
      for (let c = a; c <= b; c++) m[r * COLS + c] = 1;
    }
  }
  return m;
})();

/** lat ∈ [-90,90]，lon ∈ [-180,180] */
export function isLand(lat: number, lon: number): boolean {
  const r = Math.min(ROWS - 1, Math.max(0, Math.floor(((90 - lat) / 180) * ROWS)));
  let c = Math.floor(((lon + 180) / 360) * COLS);
  c = ((c % COLS) + COLS) % COLS;
  return mask[r * COLS + c] === 1;
}

